"""
results_clean/novelty2/summary.md (+ summary.json, val_curves.png) from experiments/novelty_fix/
(CONSTRAINTS.md Amendments 2026-11-20 (j)). Same evaluation path as results_clean/canonical.csv: prepare_pair target-test
windows, target-train stats, src.evaluate.evaluate_model -> src.utils.metrics, original units. Baselines are read
from canonical.csv and recomputed here from the same windows as a check. Noise rule of results_clean/noise_rule.md,
reference R = (a). Only seeds complete for all four methods are reported. A hand-written paragraph
(results_clean/novelty2/narrative.md) is appended if present.

  python -m src.adarnn_fix.summarize
"""
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from src.adarnn_full.summarize import canonical, mstd, verdict
from src.evaluate import naive_mean_metrics
from src.experiment import prepare_pair
from src.run_experiments import DOMAIN_CONFIGS
from src.utils.metrics import evaluate_all
from src.evaluate import denorm

EXP = Path("experiments/novelty_fix")
OLD = Path("experiments/novelty_adarnn")
OUT = Path("results_clean/novelty2")
METHODS = ["source_only", "coral", "adarnn10", "adarnn0"]
LABEL = {"source_only": "(a) GRU source-only, target-train stats", "coral": "(b) GRU + CORAL λ=10",
         "adarnn10": "(c) GRU + AdaRNN step-matched λ=10", "adarnn0": "(d) GRU + AdaRNN step-matched λ=0"}
SEEDS = [0, 1, 2]
COLORS = {"source_only": "#2a78d6", "adarnn10": "#eb6834", "adarnn0": "#1baf7a"}


def f3(x):
    return f"{x:.3f}"


def baselines():
    can = canonical()
    out = {}
    cfg = DOMAIN_CONFIGS["climate"]
    _, _, tt, _ = prepare_pair(cfg)
    st = tt["norm_stats"]
    rec = {"naive train-mean (target-train stats)": naive_mean_metrics(tt["Y_test"], st),
           "persistence (last observed value repeated)":
               evaluate_all(denorm(tt["Y_test"], st), denorm(np.repeat(tt["X_test"][:, -1:], tt["Y_test"].shape[1], 1), st))}
    for k, m in rec.items():
        c = can[("climate", k)]
        cm, cr = float(c["MAE_mean"]), float(c["RMSE_mean"])
        assert abs(cm - m["MAE"]) < 1e-3 and abs(cr - m["RMSE"]) < 1e-3, (k, cm, m)
        out[k] = {"MAE": cm, "RMSE": cr, "recomputed": m}
    return out, int(len(tt["Y_test"]))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    runs = {m: {s: json.load(open(EXP / m / f"seed{s}.json")) for s in SEEDS if (EXP / m / f"seed{s}.json").exists()}
            for m in METHODS}
    complete = [s for s in SEEDS if all(s in runs[m] for m in METHODS)]
    partial = sorted({(m, s) for m in METHODS for s in SEEDS if s in runs[m] and s not in complete})
    base, n_test = baselines()
    for m in METHODS:
        for s in complete:
            assert runs[m][s]["n_target_test_windows"] == n_test
    met = {m: {k: [runs[m][s]["target_test"]["target_stats"][k] for s in complete] for k in ["MAE", "RMSE"]} for m in METHODS}

    L = ["# Novelty fix: step-matched AdaRNN on climate (Shimla → Delhi), GRU", "",
         "Pre-registered in CONSTRAINTS.md Amendments 2026-11-20 (j). Target test set (" + str(n_test) + " windows, identical for all",
         "rows), target-train-stat normalisation, MAE/RMSE in °C via `src.evaluate.evaluate_model` on `prepare_pair` windows",
         "(the canonical.csv path). Mean ± sample std (ddof=1) over the complete seeds " + str(complete) + ". All methods: 47",
         "optimizer steps per epoch, cap 60 (joint) epochs, early stopping on source val MSE (patience 3, min Δ 1e-5,",
         "best weights restored); AdaRNN rows add 3 MSE-only pretrain epochs outside the cap. Generated by",
         "`src/adarnn_fix/summarize.py`.", "", "## Results", "",
         "| row | n | MAE mean ± std | RMSE mean ± std | per-seed MAE | per-seed RMSE | best / stopped epoch per seed | source-val MSE per seed |",
         "|---|---|---|---|---|---|---|---|"]
    for k, v in base.items():
        L.append(f"| baseline: {k} | – | {f3(v['MAE'])} | {f3(v['RMSE'])} | | | | |")
    summ = {"complete_seeds": complete, "n_target_test_windows": n_test, "baselines": base, "methods": {}}
    for m in METHODS:
        if not complete:
            L.append(f"| **{LABEL[m]}** | 0 | not run | not run | | | | |")
            continue
        (ma, sa), (mr, sr) = mstd(met[m]["MAE"]), mstd(met[m]["RMSE"])
        ep = [f"{runs[m][s]['training']['best_epoch']}/{runs[m][s]['training']['stopped_epoch']}" for s in complete]
        sv = [runs[m][s]["source_val"]["mse_norm"] for s in complete]
        L.append(f"| **{LABEL[m]}** | {len(complete)} | {f3(ma)} ± {f3(sa)} | {f3(mr)} ± {f3(sr)} | "
                 f"{'; '.join(map(f3, met[m]['MAE']))} | {'; '.join(map(f3, met[m]['RMSE']))} | {'; '.join(ep)} | "
                 f"{'; '.join(f'{x:.5f}' for x in sv)} |")
        summ["methods"][m] = {"label": LABEL[m], "MAE": met[m]["MAE"], "RMSE": met[m]["RMSE"], "epochs_best_stopped": ep,
                              "source_val_mse": sv}
    # 20-epoch reference rows (CONSTRAINTS.md 2026-11-15 (h)), same evaluation path
    L += ["", "Reference rows, earlier 20-epoch protocol (15 AdaRNN steps/epoch; `experiments/novelty_adarnn/climate/`):", "",
          "| reference row (20-epoch cap) | n | MAE mean ± std | RMSE mean ± std | best / stopped epoch per seed |", "|---|---|---|---|---|"]
    for lab, d in [("GRU source-only, target-train stats", "source_only"), ("GRU + CORAL λ=10", "coral"),
                   ("GRU + faithful AdaRNN λ=10", "adarnn")]:
        js = [json.load(open(OLD / "climate" / d / f"seed{s}.json")) for s in SEEDS]
        (ma, sa), (mr, sr) = mstd([j["target_test"]["target_stats"]["MAE"] for j in js]), mstd([j["target_test"]["target_stats"]["RMSE"] for j in js])
        L.append(f"| {lab} | 3 | {f3(ma)} ± {f3(sa)} | {f3(mr)} ± {f3(sr)} | "
                 f"{'; '.join(f'{j['training']['best_epoch']}/{j['training']['stopped_epoch']}' for j in js)} |")
    g = json.load(open(OLD / "grid" / "climate_adarnn_lam0_seed0.json"))
    L.append(f"| GRU + faithful AdaRNN λ=0 (grid, seed 0 only) | 1 | {f3(g['target_test']['target_stats']['MAE'])} | "
             f"{f3(g['target_test']['target_stats']['RMSE'])} | {g['training']['best_epoch']}/{g['training']['stopped_epoch']} |")

    # noise rule
    L += ["", "## Noise rule (results_clean/noise_rule.md), reference R = (a)", "",
          "| method vs (a) | metric | mean(M) | mean(R) | d | paired diffs (per seed) | s_R | s_M | direction | verdict |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    summ["noise_rule"] = []
    comps = [(m, "source_only") for m in ["coral", "adarnn10", "adarnn0"]]
    if len(complete) >= 2:
        for m, r in comps + [("adarnn10", "adarnn0")]:
            if (m, r) == ("adarnn10", "adarnn0"):
                L += ["", "Extra (same rule, R = (d)): does the matching term add anything beyond the schedule?", "",
                      "| method vs (d) | metric | mean(M) | mean(R) | d | paired diffs (per seed) | s_R | s_M | direction | verdict |",
                      "|---|---|---|---|---|---|---|---|---|---|"]
            for k in ["MAE", "RMSE"]:
                M, R = np.array(met[m][k]), np.array(met[r][k])
                (mM, sM), (mR, sR) = mstd(M), mstd(R)
                d = mM - mR
                dirn = "lower error" if d < 0 else ("higher error" if d > 0 else "equal")
                v = verdict(d, sR, sM)
                L.append(f"| {LABEL[m]} | {k} | {f3(mM)} | {f3(mR)} | {d:+.3f} | {'; '.join(f'{x:+.3f}' for x in M - R)} | "
                         f"{f3(sR)} | {f3(sM)} | {dirn} | {v} |")
                summ["noise_rule"].append({"method": m, "reference": r, "metric": k, "d": d, "s_R": sR, "s_M": sM,
                                           "direction": dirn, "verdict": v})
        crit = [x for x in summ["noise_rule"] if x["method"] == "adarnn10" and x["reference"] == "source_only"]
        ok = {x["metric"]: (x["direction"] == "lower error" and x["verdict"] in ("exceeds both stds",)) for x in crit}
        summ["success_criterion"] = ok
        L += ["", f"**Pre-registered success criterion** ((c) beats (a) under the noise rule): MAE "
                  f"{'met' if ok['MAE'] else 'not met'}, RMSE {'met' if ok['RMSE'] else 'not met'} "
                  "(counted as met only if (c) has lower error and the verdict is 'exceeds both stds')."]
    else:
        L.append("| – | – | | | | | | | | fewer than 2 complete seeds: no verdict |")

    # figure
    fig, ax = plt.subplots(figsize=(6.4, 3.6), dpi=150)
    for m in ["source_only", "adarnn10", "adarnn0"]:
        for i, s in enumerate(complete):
            h = runs[m][s]["training"]
            y = h["val_mse"]
            x = np.arange(1, len(y) + 1)
            ax.plot(x, y, color=COLORS[m], lw=1.6, alpha=0.9, label=LABEL[m] if i == 0 else None)
            b = h["best_epoch"]
            ax.plot([b], [y[b - 1]], "o", ms=5, color=COLORS[m], mec="#fcfcfb", mew=1.5)
    ax.axvspan(0.5, 3.5, color="#52514e", alpha=0.08, lw=0)
    ax.text(2, 0.995, "AdaRNN pretrain", transform=ax.get_xaxis_transform(), ha="center", va="top", fontsize=7, color="#52514e")
    allv = [v for m in ["source_only", "adarnn10", "adarnn0"] for s in complete for v in runs[m][s]["training"]["val_mse"]]
    if allv:
        lo = min(allv)
        ax.set_ylim(lo * 0.97, lo * 1.6)
    ax.set_xlabel("epoch (47 optimizer steps each; AdaRNN epochs 1–3 are MSE-only pretrain)", fontsize=8, color="#52514e")
    ax.set_ylabel("source val MSE (normalised)", fontsize=8, color="#52514e")
    ax.set_title("Climate, GRU: source-validation loss per epoch (dot = restored epoch)", fontsize=9, loc="left", color="#0b0b0b")
    ax.grid(axis="y", color="#e6e5e0", lw=0.6)
    for sp in ["top", "right"]:
        ax.spines[sp].set_visible(False)
    for sp in ["left", "bottom"]:
        ax.spines[sp].set_color("#c3c2b7")
    ax.tick_params(labelsize=7, colors="#52514e")
    ax.legend(fontsize=7, frameon=False, loc="upper right")
    fig.tight_layout()
    fig.savefig(OUT / "val_curves.png", facecolor="#fcfcfb")
    L += ["", "![validation loss curves](val_curves.png)", ""]

    # not run
    nr = [f"{LABEL[m]} / seed {s}" for s in SEEDS if s not in complete for m in METHODS]
    L += ["## Not run", ""] + ([f"- {x}" for x in nr] if nr else ["- nothing: all 4 methods × seeds 0-2 finished."])
    if partial:
        L.append(f"- Finished but not reported (seed incomplete for the four methods): {partial}")
    summ["not_run"] = nr
    narr = OUT / "narrative.md"
    if narr.exists():
        L += ["", narr.read_text(encoding="utf-8")]
    (OUT / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    json.dump(summ, open(OUT / "summary.json", "w"), indent=1)
    print("\n".join(L))


if __name__ == "__main__":
    main()
