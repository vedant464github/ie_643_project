"""
results_clean/novelty/summary.md (+ summary.json) from experiments/novelty_adarnn/. Same evaluation path as the
canonical results (target-test windows from prepare_pair, original units, MAE/RMSE from src.utils.metrics), the
persistence/naive baselines and TCN reference rows read from results_clean/canonical.csv, and the noise rule of
results_clean/noise_rule.md. A hand-written narrative (results_clean/novelty/narrative.md) is appended if present.

  python -m src.adarnn_full.summarize
"""
import csv
import json
from pathlib import Path

import numpy as np

EXP = Path("experiments/novelty_adarnn")
OUT = Path("results_clean/novelty")
DOMAINS = ["climate", "energy", "finance", "finance_vol"]
SEEDS = [0, 1, 2]
UNIT = {"energy": "MW", "climate": "°C", "finance": "log-return", "finance_vol": "|log-return|"}
GRU_ROWS = [("(a) GRU source-only, source stats", "source_only", "source_stats"),
            ("(b) GRU source-only, target-train stats", "source_only", "target_stats"),
            ("(c) GRU + CORAL (last hidden state)", "coral", "target_stats"),
            ("(d) GRU + faithful AdaRNN", "adarnn", "target_stats")]
TCN_ROWS = ["source-only, source stats", "source-only, target-train stats", "CORAL lambda=10",
            "AdaRNN-style lambda=10", "target-only (labels, reference)"]
REF = "(b) GRU source-only, target-train stats"


def fmt(x, d):
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return ""
    return f"{x:.6f}" if d.startswith("finance") else (f"{x:.2f}" if d == "energy" else f"{x:.3f}")


def mstd(v):
    v = np.asarray(v, float)
    return float(v.mean()), float(v.std(ddof=1)) if len(v) > 1 else float("nan")


def verdict(d, sR, sM):
    a = abs(d)
    if a > max(sR, sM):
        return "exceeds both stds"
    if sR < a <= sM:
        return "exceeds the target-stats std only"
    if a <= min(sR, sM):
        return "within both"
    return "within the target-stats std (exceeds method std)"


def canonical():
    rows = {}
    with open("results_clean/canonical.csv", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            rows[(r["domain"], r["setting"])] = r
    return rows


def gru_runs(d):
    out, meta = {}, {}
    for label, method, stats in GRU_ROWS:
        per = {}
        for s in SEEDS:
            p = EXP / d / method / f"seed{s}.json"
            if p.exists():
                j = json.load(open(p))
                per[s] = j["target_test"][stats]
                meta[(method, s)] = j
        out[label] = per
    return out, meta


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    can = canonical()
    proto = json.load(open(EXP / "energy_protocol.json")) if (EXP / "energy_protocol.json").exists() else None
    L = ["# Novelty assessment: faithful AdaRNN on a GRU vs same-backbone baselines", "",
         "Pre-registered in CONSTRAINTS.md Amendments 2026-11-15 (h). Target test set, original units, mean ± sample std",
         "(ddof=1) over seeds 0-2; target-train-stat normalisation for (b)-(d). Generated by `src/adarnn_full/summarize.py`",
         "from `experiments/novelty_adarnn/`. Baselines and TCN rows are copied from `results_clean/canonical.csv`",
         "(same target-test windows). 'not run' = no result JSON (reason in the last section).", ""]
    if proto:
        L += [f"Energy protocol: **{proto['protocol']}** (max first-epoch time of the 3 parallel GRU+AdaRNN runs "
              f"{proto['max_first_epoch_seconds']:.1f} s; rule ≤150 s → full).", ""]
    summary, verdicts, notrun = {}, [], []
    for d in DOMAINS:
        runs, meta = gru_runs(d)
        sel_p = EXP / f"lambda_selection_{d}.json"
        sel = json.load(open(sel_p)) if sel_p.exists() else None
        L += [f"## {d} (unit: {UNIT[d]})", ""]
        if sel:
            L.append(f"λ chosen (seed-0 source-val rule): CORAL {sel['coral']['chosen_lambda']}, AdaRNN "
                     f"{sel['adarnn']['chosen_lambda']}. Ratios to λ=0: CORAL "
                     + ", ".join(f"{k}: {v['ratio_to_lambda0']:.3f}" for k, v in sel["coral"]["table"].items())
                     + "; AdaRNN " + ", ".join(f"{k}: {v['ratio_to_lambda0']:.3f}" for k, v in sel["adarnn"]["table"].items()) + ".")
            L.append("")
        L += ["| row | n | MAE mean ± std | RMSE mean ± std | MAE % naive | per-seed MAE |", "|---|---|---|---|---|---|"]
        naive = float(can[(d, "naive train-mean (target-train stats)")]["MAE_mean"])
        for (dd, setting), r in can.items():
            if dd == d and r["n_seeds"] == "deterministic":
                L.append(f"| baseline: {setting} | – | {fmt(float(r['MAE_mean']), d)} | {fmt(float(r['RMSE_mean']), d)} | "
                         f"{100 * float(r['MAE_mean']) / naive:.1f} | |")
        stats = {}
        for label, method, _ in GRU_ROWS:
            per = runs[label]
            missing = [s for s in SEEDS if s not in per]
            for s in missing:
                notrun.append(f"{d} / {label} / seed {s}")
            if not per:
                L.append(f"| **{label}** | 0 | not run | not run | | |")
                continue
            mae = [per[s]["MAE"] for s in sorted(per)]
            rmse = [per[s]["RMSE"] for s in sorted(per)]
            stats[label] = {"MAE": mstd(mae), "RMSE": mstd(rmse), "per_MAE": mae, "per_RMSE": rmse, "seeds": sorted(per)}
            note = f" (seeds {sorted(per)})" if missing else ""
            L.append(f"| **{label}**{note} | {len(per)} | {fmt(stats[label]['MAE'][0], d)} ± {fmt(stats[label]['MAE'][1], d)} | "
                     f"{fmt(stats[label]['RMSE'][0], d)} ± {fmt(stats[label]['RMSE'][1], d)} | "
                     f"{100 * stats[label]['MAE'][0] / naive:.1f} | {'; '.join(fmt(v, d) for v in mae)} |")
        for t in TCN_ROWS:
            r = can[(d, t)]
            L.append(f"| TCN reference: {t} | {r['n_seeds']} | {fmt(float(r['MAE_mean']), d)} ± {fmt(float(r['MAE_std']), d)} | "
                     f"{fmt(float(r['RMSE_mean']), d)} ± {fmt(float(r['RMSE_std']), d)} | {100 * float(r['MAE_mean']) / naive:.1f} | |")
        L.append("")
        # noise rule vs (b)
        if REF in stats:
            L += ["Noise rule (results_clean/noise_rule.md) vs (b):", "",
                  "| method | metric | d = mean diff | paired diffs | s_R | s_M | direction | verdict |", "|---|---|---|---|---|---|---|---|"]
            for label in [GRU_ROWS[2][0], GRU_ROWS[3][0]]:
                if label not in stats:
                    continue
                for m in ("MAE", "RMSE"):
                    R, M = stats[REF], stats[label]
                    dd = M[m][0] - R[m][0]
                    common = [s for s in M["seeds"] if s in R["seeds"]]
                    pairs = [M[f"per_{m}"][M["seeds"].index(s)] - R[f"per_{m}"][R["seeds"].index(s)] for s in common]
                    v = verdict(dd, R[m][1], M[m][1]) if len(M["seeds"]) > 1 else "n/a (one seed)"
                    dirn = "equal" if abs(dd) < 1e-12 else ("lower error" if dd < 0 else "higher error")
                    L.append(f"| {label} | {m} | {fmt(dd, d)} | {'; '.join(fmt(p, d) for p in pairs)} | {fmt(R[m][1], d)} | "
                             f"{fmt(M[m][1], d)} | {dirn} | {v} |")
                    verdicts.append({"domain": d, "method": label, "metric": m, "d": dd, "sR": R[m][1], "sM": M[m][1],
                                     "verdict": v, "direction": dirn})
            L.append("")
        # AdaRNN diagnostics: alpha concentration at the best epoch
        ada = [meta[k] for k in sorted(meta) if k[0] == "adarnn"]
        if ada:
            L.append("AdaRNN importance weights at the restored epoch (max α over time steps, mean over the 6 pairs; "
                     "uniform = 1/V): " + "; ".join(
                         f"seed {j['seed']}: {np.mean([max(r) for r in j['training']['alpha_at_best_epoch']]):.4f} "
                         f"(1/V = {1 / j['training']['V']:.4f}, best epoch {j['training']['best_epoch']}/"
                         f"{j['training']['stopped_epoch']})" for j in ada if j['training']['alpha_at_best_epoch']) + ".")
            L.append("")
        summary[d] = {k: {"MAE": v["MAE"], "RMSE": v["RMSE"], "seeds": v["seeds"]} for k, v in stats.items()}
    L += ["## Not run", ""] + ([f"- {x}" for x in notrun] or ["- nothing"]) + [""]
    nar = OUT / "narrative.md"
    if nar.exists():
        L += [nar.read_text(encoding="utf-8")]
    (OUT / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    json.dump({"rows": summary, "verdicts": verdicts, "not_run": notrun}, open(OUT / "summary.json", "w"), indent=1)
    print("\n".join(L))


if __name__ == "__main__":
    main()
